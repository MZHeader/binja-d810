#!/usr/bin/env python3
"""Generate the opaque-predicate corpus: C source plus a manifest.

Each function is `if (P) return LIVE; return DEAD;` (or the mirrored `if (!(P))`), with P a condition
whose value never changes. Intermediates pass through an empty asm barrier so the compiler cannot
see through the predicate. Every predicate's value is proven here before it is emitted.

Usage: uv run python tests/samples/gen_opaque.py --out tests/samples/build
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from binja_d810.deadline import Deadline  # noqa: E402
from binja_d810.ir.parse import parse  # noqa: E402
from binja_d810.semantic.constancy import constant_value  # noqa: E402
from binja_d810.semantic.verify import Verdict  # noqa: E402

LIVE, DEAD = "x + y", "x ^ z ^ 0x5a"
WIDTHS = {"x": 32, "y": 32, "z": 32}


@dataclass(frozen=True)
class Predicate:
    name: str
    family: str
    temps: tuple[tuple[str, str], ...]  # (name, C expression), each followed by the barrier
    condition: str  # C, over the temps
    ir: str  # the same condition over x, y, z, in binja_d810's IR syntax (for the proof)
    value: int


PREDICATES = [
    Predicate("parity_next", "parity", (("t", "x * (x + 1)"),), "(t & 1) == 0", "eq((x * (x + 1)) & 1, 0)", 1),
    Predicate("parity_prev", "parity", (("t", "x * (x - 1)"),), "(t & 1) != 0", "ne((x * (x - 1)) & 1, 0)", 0),
    Predicate("square_mod4", "parity", (("t", "x * x"),), "(t & 3) != 2", "ne((x * x) & 3, 2)", 1),
    Predicate("odd_square", "parity", (("t", "(x | 1) * (x | 1)"),), "(t & 1) == 1", "eq(((x | 1) * (x | 1)) & 1, 1)", 1),
    Predicate("setnz", "d810", (("t", "x | 0x10u"),), "t != 0x0fu", "ne(x | 0x10, 0x0f)", 1),
    Predicate("setz", "d810", (("t", "x | 0x80u"),), "t == 0x7fu", "eq(x | 0x80, 0x7f)", 0),
    Predicate("setb", "d810", (("t", "x & 0x07u"),), "t < 0x08u", "ult(x & 7, 8)", 1),
    Predicate("setnz_y", "d810", (("t", "y | 0x300u"),), "t != 0xffu", "ne(y | 0x300, 0xff)", 1),
    Predicate("mba_add", "mba", (("a", "(x ^ y) + 2 * (x & y)"), ("b", "x + y")), "a == b",
              "eq((x ^ y) + 2 * (x & y), x + y)", 1),
    Predicate("mba_or", "mba", (("a", "(x & ~y) + y"), ("b", "x | y")), "a != b", "ne((x & ~y) + y, x | y)", 0),
    Predicate("mba_sub", "mba", (("a", "(x ^ y) - 2 * (~x & y)"), ("b", "x - y")), "a == b",
              "eq((x ^ y) - 2 * (~x & y), x - y)", 1),
    Predicate("mba_and", "mba", (("a", "(x | y) - (x ^ y)"), ("b", "x & y")), "a == b",
              "eq((x | y) - (x ^ y), x & y)", 1),
    Predicate("mba_xor", "mba", (("a", "(x | y) - (x & y)"), ("b", "x ^ y")), "a != b",
              "ne((x | y) - (x & y), x ^ y)", 0),
    Predicate("byte_range", "range", (("t", "x & 0xffu"),), "t <= 0xffu", "ule(x & 0xff, 0xff)", 1),
    Predicate("nonzero_odd", "range", (("t", "x | 1u"),), "t != 0u", "ne(x | 1, 0)", 1),
    Predicate("two_bits", "range", (("t", "(x ^ y) & 3u"),), "t < 4u", "ult((x ^ y) & 3, 4)", 1),
    Predicate("sign_set", "range", (("t", "x | 0x80000000u"),), "(int32_t)t < 0", "slt(x | 0x80000000, 0)", 1),
]


def verify(p: Predicate) -> None:
    found = constant_value(parse(p.ir, 1, WIDTHS), Deadline.after(30))
    if found is None or found[0] != p.value or found[1].verdict is not Verdict.PROVEN:
        raise AssertionError(f"generator bug: {p.name} is not proven to be {p.value}: {found}")


def emit(p: Predicate, mirrored: bool) -> str:
    name = f"opaque_{p.name}{'_mirrored' if mirrored else ''}"
    taken, other = (LIVE, DEAD) if p.value else (DEAD, LIVE)
    lines = [f"EXPORT uint32_t {name}(uint32_t x, uint32_t y, uint32_t z) {{", "    (void)x; (void)y; (void)z;"]
    lines += [f"    uint32_t {t} = {text}; B({t});" for t, text in p.temps]
    if mirrored:
        lines += [f"    if (!({p.condition})) return {other};", f"    return {taken};", "}", ""]
    else:
        lines += [f"    if ({p.condition}) return {taken};", f"    return {other};", "}", ""]
    return "\n".join(lines)


HEADER = (
    "// Generated by tests/samples/gen_opaque.py. Do not edit.\n"
    "#include <stdint.h>\n"
    '#define B(v) __asm__ volatile("" : "+r"(v))\n'
    "#ifdef _WIN32\n"
    "#define EXPORT __declspec(dllexport) __attribute__((noinline, used))\n"
    "#else\n"
    '#define EXPORT __attribute__((noinline, used, visibility("default")))\n'
    "#endif\n\n"
)


def write(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    functions, manifest = [], []
    for p in PREDICATES:
        verify(p)
        for mirrored in (False, True):
            functions.append(emit(p, mirrored))
            manifest.append({"name": f"opaque_{p.name}{'_mirrored' if mirrored else ''}", "family": p.family,
                             "condition": p.condition, "value": p.value, "mirrored": mirrored,
                             "live": LIVE, "dead": DEAD})
    (out_dir / "opaque.c").write_text(HEADER + "\n".join(functions))
    (out_dir / "opaque_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {len(manifest)} opaque-predicate samples to {out_dir}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    write(parser.parse_args().out)
